import { readFile, writeFile } from "node:fs/promises"
import { execFileSync } from "node:child_process"
import { parse } from "csv-parse/sync"
import { stringify } from "yaml"

interface Friend {
  name: string
  description: string
  url: string
  avatar: string
}

const columns = ["網站名字", "網站描述", "個人網站連結", "頭貼/Logo 連結", "上架"]

export function parseFriendSheet(csv: string): Friend[] {
  let hasHeader = false
  const rows: Record<string, string>[] = parse(csv, {
    bom: true,
    skip_empty_lines: true,
    columns(header: string[]) {
      if (columns.some((column) => !header.includes(column))) {
        throw new Error("Friend sheet columns do not match the original form.")
      }
      hasHeader = true
      return header
    },
  })
  if (!hasHeader) throw new Error("Friend sheet response has no CSV header.")
  return rows
    .filter((row) => row["上架"].toUpperCase() === "TRUE")
    .map((row) => {
      for (const column of ["個人網站連結", "頭貼/Logo 連結"]) {
        if (!["http:", "https:"].includes(new URL(row[column]).protocol)) {
          throw new Error(`Friend ${column} must use HTTP(S).`)
        }
      }
      return {
        name: row["網站名字"],
        description: row["網站描述"],
        url: row["個人網站連結"],
        avatar: row["頭貼/Logo 連結"],
      }
    })
}

if (import.meta.main) {
  const id =
    process.env.FRIENDSHIP_GOOGLE_SHEET_ID || "1jysz20ATsSXKfwOGHD3dJDNj7avu5NCTbpD8MWFOjtY"
  const sheet = process.env.FRIENDSHIP_GOOGLE_SHEET_NAME || "表單回覆 1"
  const url = new URL(`https://docs.google.com/spreadsheets/d/${encodeURIComponent(id)}/gviz/tq`)
  url.search = new URLSearchParams({
    tqx: "out:csv",
    sheet,
    tq: "select * where F = true",
  }).toString()
  const response = await fetch(url, { signal: AbortSignal.timeout(30_000) })
  if (!response.ok) throw new Error(`Friend sheet request failed: HTTP ${response.status}`)
  const friends = parseFriendSheet(await response.text())
  const destination = new URL("../src/data/friends.yaml", import.meta.url)
  const raw =
    "# Generated by bun run sync:friends; source: the approved Friendship Google Sheet rows.\n" +
    stringify(friends, { lineWidth: 0 })
  const next = execFileSync(
    "bun",
    ["x", "--no-install", "oxfmt", "--stdin-filepath=src/data/friends.yaml"],
    { input: raw, encoding: "utf8" },
  )
  let previous = ""
  try {
    previous = await readFile(destination, "utf8")
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error
  }
  if (previous !== next) await writeFile(destination, next)
  console.log(
    `Friendship: ${friends.length} approved entries; ${previous === next ? "unchanged" : "updated YAML"}.`,
  )
}
